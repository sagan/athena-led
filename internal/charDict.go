// PrintChar 在终端模拟显示 LED 点阵字符
// output: 输出目标 (通常是 os.Stdout)
// char: 字节切片，每个字节代表一列。
//
//	Bit 0 (1)  = 第 1 行 (顶)
//	Bit 1 (2)  = 第 2 行
//	Bit 2 (4)  = 第 3 行
//	Bit 3 (8)  = 第 4 行
//	Bit 4 (16) = 第 5 行 (底)
func PrintChar(output io.Writer, char rune) {
	const height = 5 // 硬件限制为 5 行高度
	if _, ok := charDict[char]; !ok {
		return
	}
	// 外层循环遍历行 (从顶到底: Bit 0 -> Bit 4)
	for row := range height {
		// 内层循环遍历列 (字节切片)
		for _, colByte := range charDict[char] {
			// 检查当前字节在当前行的位是否为 1
			// (colByte >> row) & 1 取出第 row 位的数值
			if (colByte>>row)&1 == 1 {
				// 亮灯 (使用实心圆点)
				fmt.Fprint(output, "● ")
			} else {
				// 灭灯 (使用空心圆点或点号，方便对齐)
				fmt.Fprint(output, "· ")
			}
		}
		// 打印完一行后换行
		fmt.Fprint(output, "\n")
	}
}
